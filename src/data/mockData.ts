export const generateDynamicSpots = (lat: number, lng: number, address: string, count: number = 8): ParkingSpot[] => {
  const spotTypes: SpotType[] = ['driveway', 'garage', 'lot', 'covered', 'street'];
  const basePrice = 5 + Math.floor(Math.random() * 10);
  
  return Array.from({ length: count }).map((_, i) => {
    // Generate random offset between -0.02 and 0.02 for lat and lng
    const offsetLat = lat + (Math.random() - 0.5) * 0.04;
    const offsetLng = lng + (Math.random() - 0.5) * 0.04;
    
    // Generate a random distance (0.1 to 3 miles)
    const distanceMiles = Number((Math.random() * 3 + 0.1).toFixed(1));
    const pricePerHour = basePrice + Math.floor(Math.random() * 8) - 2;
    const sType = spotTypes[i % spotTypes.length];
    
    return {
      id: `dynamic-spot-${i}-${Date.now()}`,
      title: `Premium ${sType.charAt(0).toUpperCase() + sType.slice(1)} Parking near ${address.split(',')[0]}`,
      description: `Convenient ${sType} spot located a short walk from your destination. Safe, well-lit, and perfect for your stay.`,
      address: `${Math.floor(Math.random() * 9999)} Local St`,
      neighborhood: 'Central',
      city: address.split(',')[0],
      state: '',
      zipCode: '',
      lat: offsetLat,
      lng: offsetLng,
      pricePerHour: Math.max(1, pricePerHour),
      pricePerDay: Math.max(1, pricePerHour) * 6,
      spotType: sType,
      allowedVehicles: ['compact', 'sedan', 'suv'],
      photos: INITIAL_PARKING_SPOTS[i % INITIAL_PARKING_SPOTS.length].photos,
      amenities: ['cctv', 'lighting'],
      host: INITIAL_PARKING_SPOTS[0].host,
      rating: Number((Math.random() * 1.5 + 3.5).toFixed(1)),
      reviewCount: Math.floor(Math.random() * 50),
      reviews: [],
      distanceMiles,
      instantBook: Math.random() > 0.5,
      isActive: true,
      accessInstructions: 'Follow the instructions sent to your email upon booking confirmation.',
      securityFeatures: ['Standard monitoring'],
      dimensions: {
        lengthFt: 18,
        widthFt: 9,
      },
    };
  });
};
